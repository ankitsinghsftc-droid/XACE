  assert(document.querySelector('[role=status][aria-live=polite]'), 'Accessible live status');
  button('Verify and configure runtime').click(); await settle();
  assert(!requests.some(x => x.endsWith('/install')), 'Runtime consent required');
  assert(document.activeElement === document.querySelector('input[type=checkbox]'), 'Consent focus');
  button('Find installed Codex').click(); await settle();
  const input = document.querySelector<HTMLInputElement>('input[type=text]')!;
  assert(input.value === 'C:/official/codex.exe' && document.activeElement === input, 'Detected path and focus');
  document.querySelector<HTMLInputElement>('input[type=checkbox]')!.checked = true;
  button('Verify and configure runtime').click(); await settle();
  button('Sign in with device code').click(); await settle();
  assert(document.activeElement?.tagName === 'A', 'Challenge link receives focus');
  assert(document.body.textContent?.includes('SECRET-CANARY'), 'Ephemeral challenge shown');
  assert(!document.querySelector('pre')!.textContent!.includes('canary'), 'Diagnostics exclude challenge');
  assert(localStorage.length === 0 && sessionStorage.length === 0, 'No browser persistence');
  button('Cancel pending operation').click(); await settle();
  assert(!document.body.textContent?.includes('SECRET-CANARY'), 'Cancel removes challenge');
  assert(document.activeElement?.tagName === 'BUTTON', 'Cancel restores focus');
  auth = { state: 'signed_in', login_state: 'completed', account: { plan_type: 'plus' } };
