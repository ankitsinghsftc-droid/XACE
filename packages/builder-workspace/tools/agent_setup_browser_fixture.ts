import { AgentSetupPanel } from '../src/panels/agent_setup_panel';

const assert = (ok: unknown, message: string) => { if (!ok) throw new Error(message); };
const settle = async () => { for (let i = 0; i < 8; i++) await new Promise(resolve => setTimeout(resolve, 0)); };
let auth: Record<string, unknown> = { state: 'signed_out', login_state: 'idle' };
let runtime: { runtime: { ready: boolean; setup_mode?: string; preferred_auth_flow?: string; message?: string }; job: { state: string; operation: string }; override_active: boolean } = { runtime: { ready: false }, job: { state: 'idle', operation: '' }, override_active: false };
const requests: string[] = [];
const supportContent = JSON.stringify({ schema: 'xace.agent_support_bundle.v1', checks: { auth: 'unknown' } }) + '\n';
let focused = false;
window.addEventListener('xace:focus-prompt', () => { focused = true; });
window.fetch = async (url, init) => {
  const path = String(url); requests.push(`${init?.method || 'GET'} ${path}`);
  let value: unknown;
  if (path === '/api/agent-support/preview') value = { preview_id: 'preview', sha256: 'a'.repeat(64), content: supportContent, expires_in_seconds: 300 };
  else if (path === '/api/agent-support/export') return new Response(supportContent, { status: 200 });
  else if (path === '/api/agent-support/clear') value = { cleared: true };
  else if (path === '/api/agent-support/diagnostics') value = { schema: 'xace.agent_diagnostics.v1' };
  else if (path.endsWith('/detect')) value = { candidate_path: 'C:/official/codex.exe' };
  else if (path.endsWith('/install')) { runtime = { ...runtime, runtime: { ...runtime.runtime, ready: true } }; value = runtime; }
  else if (path.endsWith('/start')) {
    auth = { state: 'signed_out', login_state: 'pending' };
    value = { ...auth, challenge: { flow: 'device_code', url: 'https://auth.openai.com/device?secret=canary', user_code: 'SECRET-CANARY' } };
  } else if (path.endsWith('/cancel')) { auth = { state: 'signed_out', login_state: 'cancelled' }; value = auth; }
  else if (path.endsWith('/logout')) { auth = { state: 'signed_out', login_state: 'idle' }; value = auth; }
  else if (path === '/api/agent-mode') value = { ai_mode: JSON.parse(String(init?.body)).mode, agent_mode: { ready: true }, billing: {} };
  else if (path.startsWith('/api/agent-auth')) value = auth;
  else value = runtime;
  return new Response(JSON.stringify(value), { status: 200, headers: { 'Content-Type': 'application/json' } });
};
const panel = new AgentSetupPanel();
const button = (text: string) => {
  const found = [...document.querySelectorAll('button')].find(el => el.textContent === text);
  assert(found, `Missing button ${text}`); return found!;
};
