"""
mutation_metadata_model.py — MutationMetadata
===============================================
Provenance record attached to every DSLTransaction.

Every CGS mutation produced by the GDE carries a MutationMetadata that
records who initiated it, from which CGS version, with what confidence,
and in which session. This record is stored in the CGS snapshot chain
(SchemaSnapshot.transaction_id references it) and is surfaced in the
builder UI version timeline.

## Why Metadata Matters
The GDE never silently mutates the CGS. Every change is traceable to:
    - The prompt or manual action that caused it (source)
    - The session it happened in (session_id)
    - The CGS version it was applied against (parent_cgs_hash)
    - How confident the PIL was that this was the right mutation (confidence)

This makes rollback, replay, and audit trivially possible.

## Source Vocabulary
Matches SchemaSnapshot.VALID_MUTATION_SOURCES exactly.
    "genesis"   — first CGS from Game Genesis Engine
    "prompt"    — LLM-generated from a natural language prompt (PIL)
    "manual"    — typed DSL path directly by a developer
    "migration" — applied by the save migration engine
    "rollback"  — created when restoring a prior snapshot
    "import"    — imported from an external CGS file
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from typing import Any


# ── Valid Sources ─────────────────────────────────────────────────────────────

VALID_MUTATION_SOURCES: frozenset[str] = frozenset({
    "genesis",
    "prompt",
    "manual",
    "migration",
    "rollback",
    "import",
})


# ── Mutation Metadata ─────────────────────────────────────────────────────────

@dataclass(frozen=True)
class MutationMetadata:
    """
    Immutable provenance record for one DSLTransaction.

    Attributes
    ----------
    transaction_id : str
        UUID4 hex identifier for the transaction this metadata belongs to.
        Set by the transaction that creates this metadata, or auto-generated.
    source : str
        What produced this mutation. One of VALID_MUTATION_SOURCES.
    parent_cgs_hash : str
        SHA-256 hash of the CGS at the time this mutation was submitted.
        Verified by CGSManager before the transaction is applied.
        Guards against applying a mutation to the wrong CGS version.
    schema_version_target : str
        MAJOR.MINOR.PATCH version string this mutation targets.
        Must match the current CGS version at apply time.
    session_id : str | None
        Builder session identifier. Used by HistoryManager to group
        mutations into sessions for undo/redo within a session.
    prompt_text : str | None
        The raw natural-language prompt that generated this mutation.
        None for manual DSL mutations. Stored for audit and replay.
    confidence : float
        PIL confidence score [0.0–1.0]. 1.0 for manual mutations.
        Surfaced in builder UI as "how sure was the AI about this change".
    created_at : float
        Unix timestamp when this metadata was created.
    description : str
        Human-readable one-line description of what this mutation does.
        Generated by the PIL diff_summariser or typed by the developer.
    risk_level : str
        One of: "low", "medium", "high".
        Set by the Safety & Scope Guard in PIL.
    extra : dict[str, Any]
        Arbitrary additional fields for extensibility.
        Use for things like: "mode_id", "affected_actor_ids", etc.
    """

    transaction_id:          str
    source:                  str
    parent_cgs_hash:         str
    schema_version_target:   str
    session_id:              str | None        = None
    prompt_text:             str | None        = None
    confidence:              float             = 1.0
    created_at:              float             = field(default_factory=time.time)
    description:             str               = ""
    risk_level:              str               = "low"
    extra:                   dict[str, Any]    = field(default_factory=dict)

    # ── Factory ───────────────────────────────────────────────────────────────

    @classmethod
    def create(
        cls,
        source:                str,
        parent_cgs_hash:       str,
        schema_version_target: str,
        session_id:            str | None  = None,
        prompt_text:           str | None  = None,
        confidence:            float       = 1.0,
        description:           str         = "",
        risk_level:            str         = "low",
        transaction_id:        str | None  = None,
        extra:                 dict | None = None,
    ) -> "MutationMetadata":
        """
        Creates a new MutationMetadata, auto-generating transaction_id and
        created_at if not provided.

        Raises
        ------
        ValueError
            If source is not in VALID_MUTATION_SOURCES.
            If confidence is not in [0.0, 1.0].
            If risk_level is not "low", "medium", or "high".
        """
        if source not in VALID_MUTATION_SOURCES:
            raise ValueError(
                f"Invalid mutation source '{source}'. "
                f"Valid: {sorted(VALID_MUTATION_SOURCES)}"
            )
        if not (0.0 <= confidence <= 1.0):
            raise ValueError(
                f"Confidence must be in [0.0, 1.0], got {confidence}."
            )
        if risk_level not in ("low", "medium", "high"):
            raise ValueError(
                f"risk_level must be 'low', 'medium', or 'high', "
                f"got '{risk_level}'."
            )
        if not parent_cgs_hash:
            raise ValueError(
                "parent_cgs_hash must not be empty. "
                "Pass the current CGS hash before submitting the transaction."
            )

        return cls(
            transaction_id=transaction_id or uuid.uuid4().hex,
            source=source,
            parent_cgs_hash=parent_cgs_hash,
            schema_version_target=schema_version_target,
            session_id=session_id,
            prompt_text=prompt_text,
            confidence=confidence,
            created_at=time.time(),
            description=description,
            risk_level=risk_level,
            extra=extra or {},
        )

    @classmethod
    def for_manual_edit(
        cls,
        parent_cgs_hash:       str,
        schema_version_target: str,
        description:           str        = "",
        session_id:            str | None = None,
    ) -> "MutationMetadata":
        """Shorthand for developer-typed DSL mutations. confidence=1.0, source='manual'."""
        return cls.create(
            source="manual",
            parent_cgs_hash=parent_cgs_hash,
            schema_version_target=schema_version_target,
            description=description,
            session_id=session_id,
            confidence=1.0,
        )

    @classmethod
    def for_prompt(
        cls,
        parent_cgs_hash:       str,
        schema_version_target: str,
        prompt_text:           str,
        confidence:            float,
        risk_level:            str        = "low",
        description:           str        = "",
        session_id:            str | None = None,
    ) -> "MutationMetadata":
        """Shorthand for PIL-generated mutations."""
        return cls.create(
            source="prompt",
            parent_cgs_hash=parent_cgs_hash,
            schema_version_target=schema_version_target,
            prompt_text=prompt_text,
            confidence=confidence,
            risk_level=risk_level,
            description=description,
            session_id=session_id,
        )

    # ── Queries ───────────────────────────────────────────────────────────────

    @property
    def is_ai_generated(self) -> bool:
        return self.source == "prompt"

    @property
    def is_high_risk(self) -> bool:
        return self.risk_level == "high"

    @property
    def is_high_confidence(self) -> bool:
        return self.confidence >= 0.85

    def short_id(self) -> str:
        return self.transaction_id[:8]

    def __repr__(self) -> str:
        conf = f"{self.confidence:.2f}" if self.is_ai_generated else "manual"
        return (
            f"MutationMetadata(id={self.short_id()}, "
            f"source={self.source!r}, "
            f"v={self.schema_version_target}, "
            f"confidence={conf}, "
            f"risk={self.risk_level})"
        )